type CommonProps = {
    record?: CustomerTransDocument,
    backTo: string,
    onSubmit: (data: InvoiceRequest) => Promise<void>,
    onSuccess?: () => Promise<void>,
    banner?: ReactNode,
};

const SERVER_FIELDS = ["reference_no", "trans_date", "due_date", "customer_id", "branch_id", "payment_term_id", "inventory_location_id", "exchange_rate", "lines", "accounts", "credit_limit"];

/** An invoice is fixed once paid, credited or voided. */
const isLocked = (record?: CustomerTransDocument) => !!record && (record.status !== "active" || Number(record.allocated_total) > 0
    || (record.lines ?? []).some(l => Number(l.quantity_done) > 0));

/** Reference, dates, terms and customer reference — shared by both invoice forms. */
// direct invoices pick terms in the customer section, so they pass showTerms={false}
function InvoiceDetails<T extends FieldValues>({control, record, readOnly, showTerms, extra}: {control: Control<T>, record?: CustomerTransDocument, readOnly: boolean, showTerms: boolean, extra?: ReactNode}) {
    const {t} = useSmartTranslation();
    const slice = control as unknown as Control<InvoiceRequest>;
    const [date, termId] = useWatch({control: slice, name: ["trans_date", "payment_term_id"]});
    const {data: terms} = useGetPaymentTermOptions();
    const term = terms?.find(p => p.id === termId);
    const suggestedDue = date ? dueDateOf(term, date) : undefined;
    const termOptions = (terms ?? []).filter(p => p.status === "active" || p.id === record?.payment_term_id).map(p => ({value: p.id, label: p.name}));

    return (
        <Row className="gx-3">
            <Col sm={6}>
                <TextField control={slice} name="reference_no" label={t('referenceNo')} maxLength={255} disabled={readOnly} placeholder={record ? undefined : t('autoGenerated')} />
            </Col>
            <Col sm={6}>
                <TextField control={slice} name="trans_date" label={t('invoiceDate')} type="date" required disabled={readOnly} />
            </Col>
            {showTerms && (
                <Col sm={6}>
                    <SelectField control={slice} name="payment_term_id" label={t('paymentTerms')} options={termOptions} numeric required placeholder="" disabled={readOnly} />
                </Col>
            )}
            <Col sm={6}>
                <TextField control={slice} name="due_date" label={t('dueDate')} type="date" disabled={readOnly}
                    hint={suggestedDue ? t('dueFromTerms', {date: suggestedDue}) : undefined} />
            </Col>
            <Col sm={6}>
                <TextField control={slice} name="customer_ref" label={t('customerPoNo')} maxLength={255} disabled={readOnly} />
            </Col>
            {extra}
        </Row>
    );
}

/** Under the "Invoice" title: its number once saved, and the currency it is billed in. */
function InvoiceSubtitle({record, currencyCode}: {record?: CustomerTransDocument, currencyCode?: string}) {
    const {t} = useSmartTranslation();
    return (
        <div className="invoice-doc-subtitle">
            {record ? <span className="fw-semibold text-dark"># {record.reference_no}</span> : <span>{t('newInvoice')}</span>}
            {currencyCode && <Badge bg="light" className="badge-soft-primary">{currencyCode}</Badge>}
        </div>
    );
}

/** Invoice the delivered, not-yet-invoiced quantities of a delivery note. */
export function InvoiceFromDeliveryForm({note, record, backTo, onSubmit, onSuccess, banner}: CommonProps & {note: CustomerTransDocument}) {
    const {t} = useSmartTranslation();
    const readOnly = isLocked(record);
    const {byId} = useSellableItems();
    const {data: taxContext} = useGetSalesTaxContext(note.branch_id);

    // what this invoice already bills per note line (edit)
    const mine = useMemo(() => new Map((record?.lines ?? []).map(l => [l.src_id ?? 0, Number(l.quantity)])), [record]);
    const rows: SourceRow[] = useMemo(() => (note.lines ?? []).map(line => {
        const own = mine.get(line.id) ?? 0;
        const before = Number(line.quantity_done) - own;
        return {
            id: line.id,
            code: line.item_code,
            description: line.description,
            uom: line.item?.uom ?? null,
            sourceQty: Number(line.quantity),
            before,
            available: Number(line.quantity) - before,
            unitPrice: Number(line.unit_price),
            discountPercent: Number(line.discount_percent),
        };
    }).filter(row => row.available > 0 || mine.has(row.id)), [note, mine]);

    const {control, setError, submitting, handleSubmitRequest} = useRequestForm<InvoiceRequest>({
        formOptions: {
            defaultValues: {
                reference_no: record?.reference_no ?? "",
                source_trans_id: note.id,
                trans_date: record?.trans_date ?? today(),
                due_date: record?.due_date ?? null,
                payment_term_id: record?.payment_term_id ?? note.payment_term_id,
                shipping_company_id: record?.shipping_company_id ?? note.shipping_company_id,
                customer_ref: record?.customer_ref ?? note.customer_ref ?? "",
                deliver_to: record?.deliver_to ?? note.deliver_to ?? "",
                contact_no: record?.contact_no ?? note.contact_no ?? "",
                remarks: record?.remarks ?? "",
                einvoice_submission_mode: record?.einvoice_submission_mode ?? "S",
                lines: rows.map(row => ({src_id: row.id, quantity: record ? (mine.get(row.id) ?? 0) : row.available})),
            },
        },
    });

    const lines = useWatch({control, name: "lines"});
    const {errors} = useFormState({control});
    const linesError = (errors.lines as {message?: string} | undefined)?.message;

    const totals = useMemo(() => calculateSalesTotals(
        taxContext?.tax_types ?? [],
        note.tax_included,
        rows.map((row, index) => {
            const rule = taxContext?.item_tax_categories[String(byId.get(note.lines?.find(l => l.id === row.id)?.item_id ?? 0)?.item_tax_category_id ?? "")];
            return {quantity: Number(lines?.[index]?.quantity) || 0, unit_price: row.unitPrice, discount_percent: row.discountPercent, exempt: rule?.exempt, exempt_tax_type_ids: rule?.exempt_tax_type_ids};
        }),
    ), [taxContext, note, rows, lines, byId]);

    const submit = async (values: InvoiceRequest) => {
        const billed = values.lines.filter(l => (Number(l.quantity) || 0) > 0);
        if (billed.length === 0) {
            setError("lines", {type: "manual", message: t('enterQuantityToInvoice')});
            throw new Error(t('enterQuantityToInvoice'));
        }
        try {
            await onSubmit({...values, reference_no: values.reference_no.trim(), due_date: values.due_date || null,
                customer_ref: blankToNull(values.customer_ref), remarks: blankToNull(values.remarks), lines: billed});
        } catch (e) {
            applyServerErrors(e, setError, SERVER_FIELDS.filter(f => f !== "lines"));
            throw e;
        }
    };

    return (
        <SettingsFormPage onSubmit={handleSubmitRequest({request: submit, onSuccess})} submitting={submitting} isEditing={!!record}
            backTo={backTo} readOnly={readOnly} submitLabel={record ? undefined : t('saveInvoice')}
            stickyActions actionsSummary={<DocTotal label={t('total')} amount={totals.grand_total} currencyCode={note.currency?.code} />}>
            {banner}

            <InvoiceDocLayout
                title={t('invoice')}
                subtitle={<InvoiceSubtitle record={record} currencyCode={note.currency?.code} />}
                meta={<InvoiceDetails control={control} record={record} readOnly={readOnly} showTerms />}
                billTo={(
                    <>
                        <CustomerInfo customerId={note.customer_id} />
                        {note.branch && note.branch.name !== note.customer?.name && (
                            <p className="small text-muted mt-2 mb-0">{t('branch')}: {note.branch.name}</p>
                        )}
                    </>
                )}
                shipTo={(
                    <div className="invoice-doc-party">
                        <p className="invoice-doc-party-ids">
                            {t('docType_delivery_note')} <span className="fw-semibold text-dark">{note.reference_no}</span>
                            {note.sales_order?.reference_no && <> · {t('salesOrder')} {note.sales_order.reference_no}</>}
                            {" · "}{note.trans_date}
                        </p>
                        {note.deliver_to && <h6 className="mb-1">{note.deliver_to}</h6>}
                        {[note.delivery_address?.address1, note.delivery_address?.address2,
                            [note.delivery_address?.postcode, note.delivery_address?.city].filter(Boolean).join(" "),
                            [note.delivery_address?.state, note.delivery_address?.country].filter(Boolean).join(", "),
                            note.contact_no].filter(Boolean).map(line => <p key={line}>{line}</p>)}
                    </div>
                )}
                itemsTitle={t('itemsToInvoice')}
                itemsHint={readOnly ? undefined : t('itemsToInvoiceHint')}
                items={(
                    <>
                        {linesError && <div className="text-danger small mb-2">{linesError}</div>}
                        <SourceLinesTable control={control} rows={rows} lineTotals={totals.lines} taxIncluded={note.tax_included} readOnly={readOnly}
                            sourceLabel={t('delivered')} beforeLabel={t('invoicedBefore')} thisLabel={t('thisInvoice')} />
                    </>
                )}
                notes={(
                    <>
                        <TextAreaField control={control} name="remarks" label={t('noteToCustomer')} rows={4} disabled={readOnly}
                            placeholder={t('noteToCustomerPlaceholder')} />
                        <EinvoiceSection control={control} readOnly={readOnly} transType="sales_invoice" customerId={note.customer_id} transId={record?.id} />
                    </>
                )}
                totals={<TotalsPanel totals={totals} taxIncluded={note.tax_included} currencyCode={note.currency?.code} />}
            />
        </SettingsFormPage>
    );
}

/** Direct invoice values: the invoice request with order-style lines (for the shared line grid). */
type DirectInvoiceValues = Omit<InvoiceRequest, "lines"> & {
    customer_id: number | null,
    branch_id: number | null,
    sales_type_id: number | null,
    sales_person_id: number | null,
    inventory_location_id: number | null,
    exchange_rate: number | null,
    delivery_address: NonNullable<InvoiceRequest["delivery_address"]>,
    lines: SalesLineRequest[],
};

function directValues(record?: CustomerTransDocument): DirectInvoiceValues {
    return {
        reference_no: record?.reference_no ?? "",
        source_trans_id: null,
        customer_id: record?.customer_id ?? null,
        branch_id: record?.branch_id ?? null,
        sales_type_id: record?.sales_type_id ?? null,
        sales_person_id: record?.sales_person_id ?? null,
        payment_term_id: record?.payment_term_id ?? null,
        inventory_location_id: record?.inventory_location_id ?? null,
        shipping_company_id: record?.shipping_company_id ?? null,
        exchange_rate: record && Number(record.exchange_rate) !== 1 ? Number(record.exchange_rate) : null,
        trans_date: record?.trans_date ?? today(),
        due_date: record?.due_date ?? null,
        customer_ref: record?.customer_ref ?? "",
        deliver_to: record?.deliver_to ?? "",
        contact_no: record?.contact_no ?? "",
        remarks: record?.remarks ?? "",
        einvoice_submission_mode: record?.einvoice_submission_mode ?? "S",
        delivery_address: {...EMPTY_DELIVERY_ADDRESS, ...(record?.delivery_address ?? {})},
        lines: record?.lines?.map(l => ({item_id: l.item_id, description: l.description, quantity: Number(l.quantity), unit_price: Number(l.unit_price), discount_percent: Number(l.discount_percent)}))
            ?? [{...EMPTY_LINE}],
    };
}

/** Invoice without a delivery note: walk-in and service sales. Stock items ship from the chosen location. */
export function DirectInvoiceForm({record, backTo, onSubmit, onSuccess, banner}: CommonProps) {
    const {t} = useSmartTranslation();
    const readOnly = isLocked(record);

    const {control, setValue, getValues, setError, submitting, handleSubmitRequest} = useRequestForm<DirectInvoiceValues>({
        formOptions: {defaultValues: directValues(record)},
    });
    const [date, lines, customerId] = useWatch({control, name: ["trans_date", "lines", "customer_id"]});
    const pricing = useDocumentPricing(control, date, lines, record?.tax_included);

    const submit = async (values: DirectInvoiceValues) => {
        try {
            await onSubmit({
                ...values,
                reference_no: values.reference_no.trim(),
                due_date: values.due_date || null,
                customer_ref: blankToNull(values.customer_ref),
                deliver_to: blankToNull(values.deliver_to),
                contact_no: blankToNull(values.contact_no),
                remarks: blankToNull(values.remarks),
                lines: values.lines.map(l => ({item_id: l.item_id, description: (l.description ?? "").trim(), quantity: l.quantity, unit_price: l.unit_price, discount_percent: l.discount_percent ?? 0})),
            });
        } catch (e) {
            applyServerErrors(e, setError, SERVER_FIELDS);
            throw e;
        }
    };

    return (
        <SettingsFormPage onSubmit={handleSubmitRequest({request: submit, onSuccess})} submitting={submitting} isEditing={!!record}
            backTo={backTo} readOnly={readOnly} submitLabel={record ? undefined : t('saveInvoice')}
            stickyActions actionsSummary={<DocTotal label={t('total')} amount={pricing.totals.grand_total} currencyCode={pricing.currency?.code} />}>
            {banner}

            <InvoiceDocLayout
                title={t('invoice')}
                subtitle={<InvoiceSubtitle record={record} currencyCode={pricing.currency?.code} />}
                meta={<InvoiceDetails control={control} record={record} readOnly={readOnly} showTerms={false}
                    extra={<ExchangeRateField control={control} pricing={pricing} savedRate={record?.exchange_rate} readOnly={readOnly} />} />}
                billTo={(
                    <>
                        <PartySection control={control} setValue={setValue} getValues={getValues} creditCheck="invoice" saved={record ?? undefined} readOnly={readOnly} />
                        <CustomerInfo customerId={customerId} />
                    </>
                )}
                shipTo={<DeliverySection control={control} readOnly={readOnly} plain />}
                itemsTitle={t('items')}
                itemsHint={pricing.taxIncluded ? t('pricesIncludeTax') : t('directInvoiceStockHint')}
                items={(
                    <SalesLinesTable control={control} setValue={setValue} items={pricing.items} byId={pricing.byId} priceList={pricing.priceList}
                        defaultDiscount={pricing.defaultDiscount} taxIncluded={pricing.taxIncluded} lineTotals={pricing.totals.lines} readOnly={readOnly} />
                )}
                notes={(
                    <>
                        <TextAreaField control={control} name="remarks" label={t('noteToCustomer')} rows={4} disabled={readOnly}
                            placeholder={t('noteToCustomerPlaceholder')} />
                        <EinvoiceSection control={control} readOnly={readOnly} transType="sales_invoice" transId={record?.id} />
                    </>
                )}
                totals={<TotalsPanel totals={pricing.totals} taxIncluded={pricing.taxIncluded} currencyCode={pricing.currency?.code} />}
            />
        </SettingsFormPage>
    );
}
